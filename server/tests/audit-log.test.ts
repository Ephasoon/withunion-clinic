describe("Viewing audit logs is not itself audited", () => {
  it("listing audit logs does not create a new audit_logs row", async () => {
    const owner = await loginAs("test.owner");
    const before = await owner.get("/api/v1/audit-logs").query({ action: "audit_log.view" });
    expect(before.body.data.total).toBe(0);

    await owner.get("/api/v1/audit-logs");
    await owner.get("/api/v1/audit-logs").query({ entity: "patients" });

    const after = await owner.get("/api/v1/audit-logs").query({ action: "audit_log.view" });
    expect(after.body.data.total).toBe(0);
  });
});
